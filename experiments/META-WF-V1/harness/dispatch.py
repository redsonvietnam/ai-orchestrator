#!/usr/bin/env python3
# harness/dispatch.py — generic scoring-run dispatch helper (CDP, deterministic).
# gen: build fill/send/presend/extract scripts for one scoring exchange.
# staging: print the staging dir path where operator/adapter writes
#   composer_readback.txt, response_text.txt, timing.json, thread_url.txt.
# No LLM click decisions: fixed templates proven in transport/t0.py.
import argparse, json, sys
from pathlib import Path

R = Path(__file__).resolve().parents[1]
GEN = R / "runs" / ".gen"
STAGING = R / "runs" / ".staging"

FILL_TMPL = """// generated by dispatch.py gen — fill composer, authoritative ProseMirror readback
const TEXT = __TEXT__;
const el = document.querySelector('#prompt-textarea.ProseMirror')
  || document.querySelector('div[contenteditable="true"].ProseMirror');
if (!el) throw new Error("composer not found: expected #prompt-textarea.ProseMirror");
if (!el.pmViewDesc || !el.pmViewDesc.node) {
  throw new Error("integrity fail: live ProseMirror document unavailable");
}
const pmDoc = el.pmViewDesc.node;
if (!pmDoc.type || pmDoc.type.name !== "doc" || typeof pmDoc.forEach !== "function") {
  throw new Error("integrity fail: unexpected ProseMirror document structure");
}

const collectTextblockText = (block) => {
  if (!block.type || !block.type.name || !block.isTextblock || typeof block.forEach !== "function") {
    throw new Error("integrity fail: unexpected top-level ProseMirror node");
  }
  let out = "";
  block.forEach((node) => {
    if (node.isText) {
      out += node.text || "";
      return;
    }
    if (node.type && node.type.name === "hard_break") {
      out += "\\n";
      return;
    }
    throw new Error(
      `integrity fail: unexpected inline ProseMirror node type=${node.type?.name || "<unknown>"}`
    );
  });
  return out.endsWith("\\r") ? out.slice(0, -1) : out;
};

const serializeProseMirror = (doc) => {
  const blocks = [];
  doc.forEach((block) => blocks.push(collectTextblockText(block)));
  if (!blocks.length) throw new Error("integrity fail: ProseMirror document has no textblocks");
  return blocks.join("\\n\\n");
};

const sha256Hex = async (text) => {
  const bytes = new TextEncoder().encode(text);
  const digest = await crypto.subtle.digest("SHA-256", bytes);
  return Array.from(new Uint8Array(digest), (b) => b.toString(16).padStart(2, "0")).join("");
};

el.focus();
await new Promise(r => setTimeout(r, 150));
document.execCommand("selectAll", false, null);

const transfer = new DataTransfer();
transfer.setData("text/plain", TEXT);
if (transfer.getData("text/plain") !== TEXT) {
  throw new Error("fill mechanism integrity fail: clipboard payload changed before dispatch");
}
const pasteEvent = new ClipboardEvent("paste", {
  bubbles: true,
  cancelable: true,
  clipboardData: transfer
});
el.dispatchEvent(pasteEvent);
await new Promise(r => setTimeout(r, 250));

if (!el.pmViewDesc || !el.pmViewDesc.node) {
  throw new Error("integrity fail: live ProseMirror document unavailable after insertion");
}
const authoritativeText = serializeProseMirror(el.pmViewDesc.node);
const authoritativeBytes = new TextEncoder().encode(authoritativeText).byteLength;
const authoritativeSha256 = await sha256Hex(authoritativeText);
const expectedSha256 = await sha256Hex(TEXT);
const exact = authoritativeText === TEXT
  && authoritativeBytes === new TextEncoder().encode(TEXT).byteLength
  && authoritativeSha256 === expectedSha256;

const innerText = el.innerText || "";
const innerTextBytes = new TextEncoder().encode(innerText).byteLength;
const innerTextSha256 = await sha256Hex(innerText);

if (!exact) {
  throw new Error(
    "FILL_EXACTNESS_FAIL: authoritative ProseMirror readback differs from frozen payload " +
    `(expected_bytes=${new TextEncoder().encode(TEXT).byteLength}, actual_bytes=${authoritativeBytes}, ` +
    `expected_sha256=${expectedSha256}, actual_sha256=${authoritativeSha256})`
  );
}

return {
  text: authoritativeText,
  bytes: authoritativeBytes,
  sha256: authoritativeSha256,
  expected_bytes: new TextEncoder().encode(TEXT).byteLength,
  expected_sha256: expectedSha256,
  exact: true,
  readback_source: "prosemirror:el.pmViewDesc.node",
  integrity_status: "PASS",
  innerText_diagnostic: {
    bytes: innerTextBytes,
    sha256: innerTextSha256,
    text_length: innerText.length
  }
};
"""

READBACK_TMPL = """// generated by dispatch.py gen — read-only authoritative ProseMirror composer readback
const el = document.querySelector('#prompt-textarea.ProseMirror')
  || document.querySelector('div[contenteditable="true"].ProseMirror');
if (!el) throw new Error("integrity fail: composer not found");
if (!el.pmViewDesc || !el.pmViewDesc.node) {
  throw new Error("integrity fail: live ProseMirror document unavailable");
}
const doc = el.pmViewDesc.node;
if (!doc.type || doc.type.name !== "doc" || typeof doc.forEach !== "function") {
  throw new Error("integrity fail: unexpected ProseMirror document structure");
}
const blocks = [];
doc.forEach((block) => {
  if (!block.isTextblock || typeof block.forEach !== "function") {
    throw new Error("integrity fail: unexpected top-level ProseMirror node");
  }
  let text = "";
  block.forEach((node) => {
    if (!node.isText) throw new Error("integrity fail: unexpected inline ProseMirror node");
    text += node.text || "";
  });
  blocks.push(text.endsWith("\\r") ? text.slice(0, -1) : text);
});
if (!blocks.length) throw new Error("integrity fail: ProseMirror document has no textblocks");
const text = blocks.join("\\n");
const bytes = new TextEncoder().encode(text);
const digest = await crypto.subtle.digest("SHA-256", bytes);
const sha256 = Array.from(new Uint8Array(digest), (b) => b.toString(16).padStart(2, "0")).join("");
const innerText = el.innerText || "";
const innerBytes = new TextEncoder().encode(innerText);
const innerDigest = await crypto.subtle.digest("SHA-256", innerBytes);
const innerSha256 = Array.from(new Uint8Array(innerDigest), (b) => b.toString(16).padStart(2, "0")).join("");
return {
  text,
  bytes: bytes.byteLength,
  sha256,
  readback_source: "prosemirror:el.pmViewDesc.node",
  innerText_diagnostic: { bytes: innerBytes.byteLength, sha256: innerSha256, text_length: innerText.length }
};
"""

SEND_TMPL = """// generated by dispatch.py gen — click send, return started_at
const btn = document.querySelector('button[data-testid="send-button"]')
  || document.querySelector('button[data-testid="chat-input-send"]')
  || document.querySelector('button[aria-label="Send message"]')
  || document.querySelector('button[aria-label="Send Message"]')
  || document.querySelector('button[aria-label*="Send"]');
if (!btn) throw new Error("send button not found");
if (btn.disabled) throw new Error("send button disabled");
btn.click();
return { clicked: true, started_at: new Date().toISOString() };
"""

PRESEND_TMPL = """// generated by dispatch.py gen — snapshot last assistant message before send
const pickLast = () => {
  const turns = document.querySelectorAll('[data-testid^="conversation-turn"]');
  if (turns.length) {
    for (let i = turns.length - 1; i >= 0; i--) {
      const t = turns[i];
      const isUser = t.querySelector('[data-testid="collapsible-user-message-root"], [data-testid="user-turn"], [data-testid="user-message"]');
      if (isUser) continue;
      const md = t.querySelector('.markdown');
      const txt = ((md || t).innerText || "").trim();
      if (txt) return txt;
    }
    return "";
  }
  const nodes = document.querySelectorAll(
    '[data-testid="assistant-message"], article');
  const last = nodes.length ? nodes[nodes.length - 1] : null;
  return last ? (last.innerText || "") : "";
};
return pickLast();
"""

EXTRACT_TMPL = """// generated by dispatch.py gen — bounded wait + final readback; never imply partial capture is complete
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const PRE = __PRE__;
const MAX_WAIT_MS = 180000;
const STABILITY_MS = 3000;
const VERIFY_MAX_MS = 30000;
const pickLast = () => {
  const turns = document.querySelectorAll('[data-testid^="conversation-turn"]');
  if (turns.length) {
    for (let i = turns.length - 1; i >= 0; i--) {
      const t = turns[i];
      const isUser = t.querySelector('[data-testid="collapsible-user-message-root"], [data-testid="user-turn"], [data-testid="user-message"]');
      if (isUser) continue;
      const md = t.querySelector('.markdown');
      const txt = ((md || t).innerText || "").trim();
      if (txt) return txt;
    }
    return "";
  }
  const nodes = document.querySelectorAll('[data-testid="assistant-message"], article');
  const last = nodes.length ? nodes[nodes.length - 1] : null;
  return last ? (last.innerText || "") : "";
};
const streamingGone = () => {
  const s = document.querySelector('.result-streaming')
    || document.querySelector('[data-testid="result-streaming"]');
  const stop = document.querySelector('button[aria-label*="Stop"]')
    || document.querySelector('button[data-testid="stop-button"]')
    || document.querySelector('button[aria-label*="stop"]')
    || document.querySelector('button[aria-label*="Dừng"]');
  return !s && !stop;
};
const startedAt = Date.now();
let prev = pickLast();
let stableSince = Date.now();
let changed = prev !== PRE;
let streamEnded = streamingGone();
let timedOut = false;

while (Date.now() - startedAt < MAX_WAIT_MS) {
  const cur = pickLast();
  if (cur && cur !== PRE) changed = true;
  streamEnded = streamingGone();
  if (changed && streamEnded && cur && cur === prev) {
    if (Date.now() - stableSince >= STABILITY_MS) break;
  } else {
    if (cur !== prev) stableSince = Date.now();
    prev = cur;
  }
  await sleep(1000);
}

if (Date.now() - startedAt >= MAX_WAIT_MS) timedOut = true;

// Mandatory final DOM/message readback at budget expiry (or immediately after normal exit).
const finalText = pickLast();
const finalStreamEnded = streamingGone();
if (!finalText || finalText === PRE) {
  return {
    text: finalText || "",
    finished_at: new Date().toISOString(),
    model: null,
    extraction_status: "EXTRACTION_FAIL",
    reason: timedOut ? "no new response by 180s hard budget" : "no new response extracted",
    timed_out: timedOut,
    stream_ended: finalStreamEnded
  };
}

let text = finalText;
let verifyStartedAt = Date.now();
let stable = false;
while (Date.now() - verifyStartedAt < VERIFY_MAX_MS) {
  await sleep(1000);
  const again = pickLast();
  if (!again || again === PRE) {
    return {
      text: "",
      finished_at: new Date().toISOString(),
      model: null,
      extraction_status: "EXTRACTION_FAIL",
      reason: "response vanished during final verification",
      timed_out: timedOut,
      stream_ended: streamingGone()
    };
  }
  if (again === text) {
    stable = true;
    break;
  }
  text = again;
}

const modelEl = document.querySelector('[data-testid="model-switcher-button"]')
  || document.querySelector('button[aria-haspopup="menu"][aria-label*="mode" i]');
const streamEndedAtReadback = streamingGone();
const extractionStatus = !timedOut && streamEndedAtReadback && stable
  ? "EXTRACTION_PASS"
  : "EXTRACTION_FAIL";
const reason = extractionStatus === "EXTRACTION_PASS"
  ? null
  : (timedOut
      ? "hard 180s budget expired before a confirmed complete response"
      : (!streamEndedAtReadback
          ? "streaming marker/stop control still present at final readback"
          : "response did not stabilize during final verification"));

return {
  text,
  finished_at: new Date().toISOString(),
  model: modelEl ? (modelEl.innerText || "").trim().slice(0, 80) : null,
  extraction_status: extractionStatus,
  reason,
  timed_out: timedOut,
  stream_ended: streamEndedAtReadback,
  stable
};
"""


def cmd_gen(a):
    GEN.mkdir(parents=True, exist_ok=True)
    prompt = Path(a.prompt)
    prompt_text = prompt.read_text(encoding="utf-8")
    pre = Path(a.pre).read_text(encoding="utf-8", errors="replace") if a.pre else ""
    prefix = f"{a.workflow}_{a.name}"
    files = {
        f"fill_{prefix}.js": FILL_TMPL.replace("__TEXT__", json.dumps(prompt_text)),
        f"readback_{prefix}.js": READBACK_TMPL,
        f"send_{prefix}.js": SEND_TMPL,
        f"presend_{prefix}.js": PRESEND_TMPL,
        f"extract_{prefix}.js": EXTRACT_TMPL.replace("__PRE__", json.dumps(pre)),
    }
    for n, body in files.items():
        (GEN / n).write_text(body, encoding="utf-8")
    print(json.dumps({"generated": sorted(files),
                      "prompt_chars": len(prompt_text),
                      "pre_chars": len(pre)}, indent=2))


def cmd_staging(a):
    d = STAGING / f"{a.workflow}_{a.name}"
    d.mkdir(parents=True, exist_ok=True)
    print(str(d))


def main():
    p = argparse.ArgumentParser()
    sub = p.add_subparsers(dest="cmd", required=True)
    g = sub.add_parser("gen")
    g.add_argument("workflow")
    g.add_argument("name")
    g.add_argument("provider")
    g.add_argument("--prompt", required=True)
    g.add_argument("--pre")
    g.set_defaults(fn=cmd_gen)
    s = sub.add_parser("staging")
    s.add_argument("workflow")
    s.add_argument("name")
    s.set_defaults(fn=cmd_staging)
    a = p.parse_args()
    a.fn(a)


if __name__ == "__main__":
    main()
